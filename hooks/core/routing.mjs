// claude.ai Artifact pages (#938) are a client-rendered SPA shell gated
// behind the caller's authenticated claude.ai session. Native WebFetch has
// a documented exception for these URLs — it fetches them using that
// session — while open_ctx_fetch_and_index does a bare unauthenticated fetch and
// can only ever retrieve the empty shell (~0.1KB, no real content). Parsed
// via the URL constructor (not a substring/regex check on the raw string)
// so a lookalike host like claude.ai.evil.com can't slip through.
function isClaudeArtifactUrl(url) {
  if (typeof url !== "string" || url === "") return false;
  let parsed;
  try {
    parsed = new URL(url);
  } catch {
    return false;
  }
  if (parsed.protocol !== "https:") return false;
  if (parsed.hostname !== "claude.ai" && parsed.hostname !== "preview.claude.ai") return false;
  return parsed.pathname.startsWith("/code/artifact/");
}

// #908: hosts the operator wants to keep on the platform's NATIVE fetch path.
// OPEN_CONTEXT_MODE_WEBFETCH_NATIVE_DOMAINS=claude.ai,internal.example.com —
// comma-separated, matched against the URL host exactly or as a subdomain, so
// `preview.claude.ai` counts and `claude.ai.evil.com` does not. These URLs
// are short, one-off or auth-gated, where the index round-trip is pure
// overhead. #1003's OPEN_CONTEXT_MODE_DISABLE_WEBFETCH_REDIRECT is the blunt
// version: it drops the redirect for every host to spare these few. Config in
// env rather than a new file, like every other knob here, so it survives a
// plugin upgrade (hand-editing hooks.json inside the versioned cache does not).
const NATIVE_FETCH_DOMAINS_ENV = "OPEN_CONTEXT_MODE_WEBFETCH_NATIVE_DOMAINS";

function nativeFetchDomains() {
  const raw = process.env[NATIVE_FETCH_DOMAINS_ENV];
  if (typeof raw !== "string" || raw === "") return [];
  return raw
    .split(",")
    .map((domain) => domain.trim().toLowerCase())
    .filter((domain) => domain !== "");
}

function isNativeFetchDomain(url) {
  if (typeof url !== "string" || url === "") return false;
  let parsed;
  try {
    parsed = new URL(url);
  } catch {
    return false;
  }
  if (parsed.protocol !== "https:" && parsed.protocol !== "http:") return false;
  const host = parsed.hostname.toLowerCase();
  return nativeFetchDomains().some((domain) => host === domain || host.endsWith(`.${domain}`));
}

/**
 * True when every http(s) token in a command segment points at an
 * operator-excluded host, so the segment can stay on the platform's native
 * curl/wget (#908). Requiring ALL of them is what keeps this safe: a segment
 * that merely mentions an excluded host — a JSON body, a header value, an
 * unrelated second URL — keeps the redirect. No literal URL at all (a shell
 * variable, a redirect target) is not a match either, so those stay
 * redirected, which is the direction that cannot flood context.
 */
function segmentTargetsOnlyNativeFetchDomains(segment) {
  const urls = segment.match(/https?:\/\/[^\s'"\\)]+/gi);
  if (!urls || urls.length === 0) return false;
  return urls.every((url) => isNativeFetchDomain(url));
}

