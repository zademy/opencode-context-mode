/**
 * Guard for actions that redirect to MCP tools (#230).
 * If MCP server isn't ready, returns null (passthrough) instead of the
 * redirect action — prevents agent from getting stuck when MCP tools
 * are unavailable. Applies to deny and modify actions that mention MCP alternatives.
 */
function mcpRedirect(result, mcpToolsAvailable = true, platform, embeddedTools = false) {
  // #1037: an operator can turn every redirect off. The redirect exists to
  // protect the context window; it must never be the reason a caller cannot
  // reach the network at all. A subagent whose tool set does not include the
  // open_ctx_* tools is redirected to tools it cannot call, and the caller is left
  // with no way to do web research and no way to say so.
  if (process.env.OPEN_CONTEXT_MODE_ALLOW_WEBFETCH === "1") return null;
  if (!mcpToolsAvailable) return null;
  // Claude Code launches the MCP server and the hooks from the same session
  // process, so the server's host must be one of our ancestors. A live server
  // from a sibling session does not make open_ctx_* callable here (#1055). Other
  // hosts keep the machine-wide check: their spawn topology is not verified.
  // #1053: in plugin-only embedded mode the process running this routing
  // IS the one that registered the open_ctx_* tools in-process — there is no MCP
  // server process, the readiness sentinel never exists, and the gate below
  // is permanently false, silently swallowing every redirect. The host that
  // embedded the tools asserts embeddedTools because it registered them by
  // construction; the sentinel check stays for every hook-process caller.
  if (!embeddedTools && !isMCPReady({ sessionScoped: platform === "claude-code" })) return null;
  return result;
}
