#!/usr/bin/env node
/**
 * Regenerates src/dashboard/styles.ts (the committed CSS artifact ui.ts
 * inlines) from src/dashboard/tailwind.css. Run via `npm run tailwind`;
 * `npm run build` runs it first so class edits in ui.ts can never drift.
 */
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const bin = join(root, "node_modules", ".bin", process.platform === "win32" ? "tailwindcss.cmd" : "tailwindcss");
const tmpCss = join(root, "src", "dashboard", ".styles.tmp.css");

execFileSync(
  bin,
  ["-i", "src/dashboard/tailwind.css", "-o", "src/dashboard/.styles.tmp.css", "--minify"],
  // Node refuses to spawnSync .cmd shims without a shell since the 2024
  // batch-file injection patch (EINVAL).
  { cwd: root, stdio: "inherit", shell: process.platform === "win32" },
);

const css = readFileSync(tmpCss, "utf8");
rmSync(tmpCss, { force: true });

const stylesPath = join(root, "src", "dashboard", "styles.ts");
writeFileSync(
  stylesPath,
  "// GENERATED by `npm run tailwind` (scripts/build-dashboard-css.mjs). Do not edit.\n" +
    `export const dashboardCss = ${JSON.stringify(css)};\n`,
);

// Tailwind output can contain double quotes, which makes Prettier prefer a
// single-quoted literal — without this pass the generated file would fail
// `npm run format:check` whenever the CSS gains its first `"`.
const prettierBin = join(root, "node_modules", ".bin", process.platform === "win32" ? "prettier.cmd" : "prettier");
if (existsSync(prettierBin)) {
  execFileSync(prettierBin, ["--write", stylesPath], { cwd: root, stdio: "ignore", shell: process.platform === "win32" });
}

console.log(`src/dashboard/styles.ts updated (${css.length} bytes of CSS)`);
